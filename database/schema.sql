-- Script de criação do schema (PostgreSQL)
-- Uso:
--   1) CREATE DATABASE vendinha;
--   2) conectar no banco vendinha e executar este arquivo:
--      psql -U postgres -d vendinha -f database/schema.sql

CREATE TABLE IF NOT EXISTS clientes (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150) NOT NULL,
    cpf            VARCHAR(11)  NOT NULL,           -- somente dígitos
    datanascimento DATE         NOT NULL,
    email          VARCHAR(200) NULL,
    CONSTRAINT uq_clientes_cpf UNIQUE (cpf)         -- não permite CPF duplicado
);

CREATE TABLE IF NOT EXISTS dividas (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clienteid      INTEGER        NOT NULL,
    valor          NUMERIC(18, 2) NOT NULL CHECK (valor > 0),
    paga           BOOLEAN        NOT NULL DEFAULT FALSE,
    datacriacao    TIMESTAMPTZ    NOT NULL,
    datapagamento  TIMESTAMPTZ    NULL,
    CONSTRAINT fk_dividas_cliente FOREIGN KEY (clienteid)
        REFERENCES clientes (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_dividas_clienteid ON dividas (clienteid);

-- Regra de negócio garantida também no banco:
-- um cliente só pode ter UMA dívida em aberto (paga = false).
CREATE UNIQUE INDEX IF NOT EXISTS ux_dividas_uma_em_aberto_por_cliente
    ON dividas (clienteid)
    WHERE paga = FALSE;
